export const GLYPH_HEIGHT = 7

export interface Layout {
  pixels: { x: number; y: number }[]
  width: number
  height: number
}

/** Lay a string out left to right, `tracking` blank columns between glyphs. */
export function layoutText(text: string, tracking = 1): Layout {
  const pixels: Layout['pixels'] = []
  let cursor = 0

  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char] ?? GLYPHS['?']
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] === '#') pixels.push({ x: cursor + x, y })
      }
    })
    cursor += glyph[0].length + tracking
  }

  return { pixels, width: Math.max(0, cursor - tracking), height: GLYPH_HEIGHT }
}
